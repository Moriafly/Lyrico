private fun filledSymbol(name: String, viewportSize: Float, baselineOffset: Float, vararg paths: String): ImageVector =
    ImageVector.Builder(name, 24.dp, 24.dp, viewportSize, viewportSize).apply {
        // Material Symbols use a baseline-relative viewport (0, -960, 960, 960).
        addGroup(translationY = baselineOffset)
        paths.forEach { data ->
            addPath(
                pathData = PathParser().parsePathString(data).toNodes(),
                fill = SolidColor(Color.Black),
            )
        }
        clearGroup()
    }.build()
